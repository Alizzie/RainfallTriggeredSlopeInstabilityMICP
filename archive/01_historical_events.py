"""
01_historical_events.py - Temporal Validation against WSL Database

This script simulates historical landslide events by extracting rainfall and soil
moisture data for the weeks surrounding a documented disaster. It validates whether
the geotechnical model correctly predicts a Factor of Safety (FoS) <= 1.0 during
the exact real-world failure window.

"""

import sys
import os

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from core import data_loader as dl
from core import physics
from core import constants as const
from pipeline.utils import constants as auct
from pipeline.utils import val_visuals as vis

PLOT_DIR = "output/event_plotting/events"
RESULTS_CSV = "output/event_plotting/validation_results.csv"
STABLE_RAIN_CSV = "output/event_plotting/validation_stable_events_by_rainfall.csv"
FOS_THRESHOLD = 1.0

# Set False to skip the ~600 individual 3-panel event plots (slow) and only
# produce the summary histogram. The per-event plots are still generated by
# default since that's the diagnostic view most useful for spot-checking.
PLOT_INDIVIDUAL_EVENTS = True

os.makedirs(PLOT_DIR, exist_ok=True)


def simulate_event(x, y, date, region_id, d_rate, et_rate, et_amp):
    """Runs the physics model for a specific coordinate and time window.

    region_id / d_rate / et_rate / et_amp are resolved ONCE by the caller (see
    main()) so they survive even if the simulation itself returns early.
    """
    if d_rate is None:
        return None  # point falls outside every calibrated region

    start = date - pd.Timedelta(days=auct.SPINUP_DAYS)
    end = date + pd.Timedelta(days=auct.WINDOW_DAYS + 5)

    # rainfall may span a year boundary; load each needed year
    years = sorted({start.year, end.year})
    rain = dl.load_rainfall(x, y, years)

    if rain is None or rain.empty:
        return None

    rain = rain.loc[start:end]
    if rain.empty:
        return None

    bafu = dl.load_bafu_moisture(region_id, interpolate_daily=False)
    bafu_win = bafu.loc[start:end] if bafu is not None else pd.Series(dtype=float)

    # Simulate daily soil saturation
    S = physics.calculate_daily_saturation(
        rain.values,
        n=const.N,
        n_perp=const.H_PERP,
        m0=const.M0,
        s_pp_onset=const.S_PP_ONSET_DEFAULT,
        drainage_rate=d_rate,
        et_rate=et_rate,
        et_amplitude=et_amp,
        day_of_year=rain.index.dayofyear.to_numpy(),
    )

    S_series = pd.Series(S, index=rain.index)
    m_pp = physics.pore_pressure_ratio(S_series.values, const.S_PP_ONSET_DEFAULT)

    # Compute FoS for the entire simulation period
    fos = pd.Series(
        physics.compute_fos(
            m_array=m_pp,
            c=const.C,
            gamma=const.GAMMA,
            gamma_w=const.GAMMA_W,
            h_v=const.H_V,
            beta_rad=const.beta,
            phi_rad=const.phi,
        ),
        index=S_series.index,
    )

    return rain, S_series, fos, bafu_win


def evaluate(fos, date):
    """Finds the minimum FoS within the defined window around the event date"""
    win = fos.loc[
        date
        - pd.Timedelta(days=auct.WINDOW_DAYS) : date
        + pd.Timedelta(days=auct.WINDOW_DAYS)
    ]

    if win.empty:
        return None, None

    return float(win.min()), win.idxmin().date()


def blank_result(ev, region_id, label="no_data"):
    """Consistent-schema row for events that couldn't be simulated."""
    return {
        "municipality": ev.get("municipality", ""),
        "date": ev["date"].date() if pd.notna(ev["date"]) else None,
        "x": ev["x"],
        "y": ev["y"],
        "min_fos": np.nan,
        "min_fos_date": None,
        "rain_max_window": np.nan,
        "label": label,
        "region_id": region_id,
        "et_rate": np.nan,
        "drainage_rate": np.nan,
    }


def main():
    """Main Execution"""
    inv = dl.load_wsl_usable_inventory()
    print(f"Loaded {len(inv)} historical events from the WSL inventory.")

    results_data = []

    for idx, ev in inv.iterrows():
        x, y = dl.to_lv95(ev["x"], ev["y"])  # idempotent: already LV95 on load

        region_id, d_rate, et_rate, et_amp = dl.get_region_params(x, y, auct.CALIB)

        simulation_out = simulate_event(
            x, y, ev["date"], region_id, d_rate, et_rate, et_amp
        )

        if simulation_out is None:
            results_data.append(blank_result(ev, region_id))
            continue

        rain, S, fos, bafu_win = simulation_out
        min_fos, min_date = evaluate(fos, ev["date"])

        if min_fos is None:
            results_data.append(blank_result(ev, region_id))
            continue

        label = "unstable" if min_fos <= FOS_THRESHOLD else "stable"

        if PLOT_INDIVIDUAL_EVENTS:
            vis.plot_event(
                rain,
                S,
                fos,
                bafu_win,
                ev["date"],
                ev.get("municipality", "event"),
                idx,
                PLOT_DIR,
                const.S_PP_ONSET_DEFAULT,
                const.C,
            )

        win_rain = rain.loc[
            ev["date"]
            - pd.Timedelta(days=auct.WINDOW_DAYS) : ev["date"]
            + pd.Timedelta(days=auct.WINDOW_DAYS)
        ]

        results_data.append(
            {
                "municipality": ev.get("municipality", ""),
                "date": ev["date"].date(),
                "x": x,
                "y": y,
                "min_fos": round(min_fos, 3),
                "min_fos_date": min_date,
                "rain_max_window": round(win_rain.max(), 1),
                "label": label,
                "region_id": region_id,
                "et_rate": et_rate,
                "drainage_rate": d_rate,
            }
        )

    res_df = pd.DataFrame(results_data)
    res_df.to_csv(RESULTS_CSV, index=False)

    # ---- Print Summary Statistics ----
    scored = res_df[res_df["label"].isin(["stable", "unstable"])]
    n = len(scored)
    detected = (scored["label"] == "unstable").sum()

    stats_file = f"{PLOT_DIR}/historical_stats.txt"
    with open(stats_file, "w", encoding="utf-8") as txt_stats:
        txt_stats.write("--- Historical Event Validation Summary ---\n")
        txt_stats.write(f"Total scored events: {n}\n")
        txt_stats.write(
            f"Overall Detection Rate: {detected}/{n} ({detected/n:.1%}) of events "
            f"had FoS <= 1 within +/-{auct.WINDOW_DAYS} days.\n"
        )

        n_no_data = (res_df["label"] == "no_data").sum()
        txt_stats.write(f"Events with no usable data: {n_no_data}\n\n")

        stable = scored[scored.label == "stable"]
        txt_stats.write(
            f"Stable events with <5mm rain in window: "
            f"{(stable['rain_max_window'] < 5).sum()} / {len(stable)}\n\n"
        )

        txt_stats.write("--- Detection Rates by Rainfall Intensity Band ---\n")
        for lo, hi in [(0, 20), (20, 40), (40, 80), (80, 999)]:
            band = scored[
                (scored.rain_max_window >= lo) & (scored.rain_max_window < hi)
            ]
            if len(band) > 0:
                det = (band.label == "unstable").mean()
                txt_stats.write(
                    f"{lo:3d}-{hi:3d} mm: {det:4.0%} detected  (n={len(band)})\n"
                )

    # ---- Stable-events-by-rainfall table (near-miss diagnostic) ----
    # Sorted highest rainfall first: these are the interesting borderline cases -
    # events the model called "stable" despite a lot of rain having fallen.
    stable_sorted = (
        scored[scored.label == "stable"]
        .sort_values("rain_max_window", ascending=False)
        .reset_index(drop=True)
    )
    stable_sorted.to_csv(STABLE_RAIN_CSV, index=False)

    # Print confirmation to console
    print(f"\nModel Detection Rate: {detected}/{n} ({detected/n:.1%})")
    print(f"Validation Results CSV saved -> {RESULTS_CSV}")
    print(f"Detailed statistics logged to -> {stats_file}")
    print(f"Stable events by rainfall (near-miss table) -> {STABLE_RAIN_CSV}")
    if PLOT_INDIVIDUAL_EVENTS:
        print(f"Event plots saved -> {PLOT_DIR}/")

    print(f"\nTop 10 stable events with the most rainfall in their window:")
    print(
        stable_sorted[
            ["municipality", "date", "region_id", "rain_max_window", "min_fos"]
        ]
        .head(10)
        .to_string(index=False)
    )

    # ---- Generate summary distribution histogram ----
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.hist(scored["min_fos"], bins=20, color="steelblue", edgecolor="k")
    ax.axvline(1.0, color="red", ls="--", label="Failure Threshold (FoS=1)")
    ax.set_xlabel("Minimum FoS within Event Window")
    ax.set_ylabel("Number of Historical Events")
    ax.set_title("Distribution of Minimum FoS During Landslides")
    ax.legend()
    fig.tight_layout()
    fig.savefig(f"{PLOT_DIR}/_summary_minfos_hist.png", dpi=150)
    plt.close(fig)
    print(f"\nSummary histogram -> {PLOT_DIR}/_summary_minfos_hist.png")


if __name__ == "__main__":
    main()
